// npm run review  ->  writes CONTENT_REVIEW.md from the data files.
// Never edit CONTENT_REVIEW.md by hand; edit the JSON and re-run this.
import { readFileSync, writeFileSync } from "node:fs";

const load = (p: string) => JSON.parse(readFileSync(p, "utf-8"));
const player = load("data/cards.json").cards;
const arius = load("data/arius-deck.json").cards;
const creed = load("data/creed.json");
const byId: Record<string, any> = Object.fromEntries(player.map((c: any) => [c.id, c]));
const slotById: Record<string, any> = Object.fromEntries(creed.slots.map((s: any) => [s.id, s]));

const workName = (q: any) =>
  q.work === "csmv" ? `On the Incarnation §${q.section} (C.S.M.V. trans.)`
                    : `Against the Arians ${["", "I", "II", "III", "IV"][q.discourse]}.${q.section} (NPNF trans.)`;
const box = (c: any) => (c.approved ? "[x]" : "[ ]");
const quote = (c: any) => (c.quote ? `> "${c.quote.text}"\n> — ${workName(c.quote)}\n` : "");

let out = `# Content Review

Generated by \`npm run review\` from the files in \`data/\`. Don't edit this file;
edit the JSON and re-run.

**What has been checked by machine:** every Athanasius quote below appears word
for word in the cited section of the source text (\`npm run validate\`).
Every Creed phrase appears word for word in the 325 text.

**What has NOT been checked:** whether each explanation is sound Orthodox
teaching and right for 13-year-olds. That's your review. When a card is good,
set \`"approved": true\` on it in the JSON file. To change wording, edit the
JSON directly or tell Claude what to change.

Scripture text is NKJV, checked word for word against the NKJV text from Bible
Gateway (saved in \`sources/nkjv-verses.json\`). The game will show Thomas
Nelson's required notice: "Scripture taken from the New King James Version®.
Copyright © 1982 by Thomas Nelson. Used by permission. All rights reserved."

## Judgment calls to look at first

1. **John 14:28 ("The Father is greater").** The brief's explanation was
   "spoken as the incarnate Son." Athanasius's own reading in *Against the
   Arians* I.58 is different: the Father is greater as the source the Son is
   begotten from, not in nature. The card follows Athanasius. If you'd rather
   teach the "in His humanity" reading (Cyril and others), say so.
2. **Proverbs 8:22.** Athanasius reads "created me" as the Son's human body
   (II.47), so John 1:14 is the main counter, with John 1:3 also accepted. The
   verse text is the Greek wording Arius used, as Athanasius quotes it. The NKJV
   says "The LORD possessed me."
3. **Acts 2:36 unlocks "God from God, Light from Light."** The pairing works
   through the Hebrews 1:3 counter (the Son as the Father's radiance), but the
   link is looser than the others.
4. **On the Incarnation cards as answers.** Four of them are now correct
   answers: King in the City (to "God Made Him Lord"), Restored Portrait (to
   "Greater Than I"), God Became Man (to "Not Even the Son Knows"), and Death
   Trampled (to "He Came to Be From Nothing"). Check that each pairing makes
   sense to you. "Worship Belongs to God" is from *Against the Arians* and is
   still partial credit only.
5. **Colossians 1:15 in the NKJV** reads "firstborn *over* all creation," which
   already leans toward the Orthodox reading. Arius used the Greek "firstborn
   *of* all creation." This challenge may feel easier than intended.
6. **The §54 line** in this translation reads "assumed humanity that we might
   become God," not the more familiar "became man."

## The 325 Creed (Robertson, public domain)

> ${creed.fullText}

Source: ${creed.source}

`;

out += `## Arius's challenges (${arius.length})\n\n`;
for (const a of arius) {
  const slot = slotById[a.unlocksSlot];
  out += `### ${box(a)} ${a.name}  \`${a.id}\`\n\n`;
  out += `**Arius plays:** ${a.scriptureRef ?? "Slogan"}: *"${a.flavor}"*  \n`;
  out += `**Card text:** ${a.text}  \n`;
  out += `**Correct counters:** ${a.counters.map((id: string) => `${byId[id].name} (${byId[id].scriptureRef ?? "argument"})`).join("; ")}  \n`;
  out += `**Unlocks Creed slot:** "${slot.phrase}"\n\n`;
  out += `**Explanation popup:** ${a.explanation}\n\n${quote(a)}\n`;
  out += `**Citation:** ${a.citation}\n\n`;
  if (a.note) out += `*Note:* ${a.note}\n\n`;
}

out += `## Creed slots (${creed.slots.length})\n\n`;
for (const s of creed.slots) {
  const by = arius.find((a: any) => a.unlocksSlot === s.id);
  out += `- ${box(s)} **${s.order}. "${s.phrase}"**: ${s.guardsAgainst} *(unlocked by beating ${by?.name})*\n`;
}
out += `\n*End of match note:* ${creed.laterNote}\n\n`;

for (const [title, type] of [["Scripture cards", "scripture"], ["Athanasius argument cards", "argument"]]) {
  const list = player.filter((c: any) => c.type === type);
  out += `## ${title} (${list.length})\n\n`;
  for (const c of list) {
    const answers = arius.filter((a: any) => a.counters.includes(c.id)).map((a: any) => a.name);
    out += `### ${box(c)} ${c.name}  \`${c.id}\`\n\n`;
    if (c.scriptureRef) out += `**${c.scriptureRef}:** *"${c.flavor}"*  \n`;
    out += `**Card text:** ${c.text}  \n`;
    out += `**Cost ${c.cost} · Power ${c.power}** · ${answers.length ? `Correct answer to: ${answers.join(", ")}` : "Not a correct answer to any challenge (partial credit only)"}\n\n`;
    out += `**Explanation:** ${c.explanation}\n\n${quote(c)}\n**Citation:** ${c.citation}\n\n`;
  }
}

writeFileSync("CONTENT_REVIEW.md", out);
console.log(`Wrote CONTENT_REVIEW.md (${player.length + arius.length} cards, ${creed.slots.length} slots)`);
